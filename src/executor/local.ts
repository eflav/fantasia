import * as fs from 'fs';
import * as path from 'path';
import { execFile } from 'child_process';
import { promisify } from 'util';
import type { Assumption, Plan, PlanStep } from '../types/index.js';

const execFileAsync = promisify(execFile);

export interface ExecContext {
  rootDir: string;
  workspaceDir: string;
  plan: Plan;
  assumptions: Assumption[];
  storyRaw: string;
}

function ensureParent(file: string): void {
  fs.mkdirSync(path.dirname(file), { recursive: true });
}

function abs(ctx: ExecContext, rel?: string): string {
  if (!rel) return ctx.workspaceDir;
  if (rel.startsWith('workspace/')) {
    return path.join(ctx.rootDir, rel);
  }
  return path.join(ctx.rootDir, rel);
}

function slugDir(ctx: ExecContext): string {
  const art = ctx.plan.steps.find((s) => s.artifact)?.artifact;
  if (art) {
    const parts = art.replace(/^workspace\//, '').split('/');
    return path.join(ctx.workspaceDir, parts[0]);
  }
  return path.join(ctx.workspaceDir, 'deliverable');
}

function storyExcerpt(ctx: ExecContext, n = 200): string {
  return ctx.storyRaw.replace(/\s+/g, ' ').trim().slice(0, n);
}

function writeAssumptionsMd(ctx: ExecContext, file: string): string {
  ensureParent(file);
  const lines = [
    '# Assumptions',
    '',
    `Story: ${storyExcerpt(ctx, 120)}`,
    '',
    'Fantasia filled gaps without asking clarifying questions:',
    '',
    ...ctx.assumptions.map((a) => `- **${a.id}**: ${a.text}  \n  _Rationale:_ ${a.rationale}`),
    '',
  ];
  fs.writeFileSync(file, lines.join('\n'), 'utf8');
  return `wrote ${file} (${ctx.assumptions.length} assumptions)`;
}

function deriveTodoItems(story: string): string[] {
  const base = [
    'Clarify goal in one sentence (self-authored)',
    'Identify primary artifact path',
    'Draft initial content',
    'Apply assumptions as constraints',
    'Self-review for completeness',
    'Mark verification criteria',
    'Record outcome for memory',
  ];
  // Pull quoted or capitalized phrases as extra items
  const extras = story
    .split(/[,.;]/)
    .map((x) => x.trim())
    .filter((x) => x.length > 8 && x.length < 60)
    .slice(0, 3)
    .map((x) => `Address: ${x}`);
  return [...base.slice(0, 5), ...extras, ...base.slice(5)].slice(0, 8);
}

function writeTodo(ctx: ExecContext, file: string, markDone: boolean): string {
  ensureParent(file);
  const items = deriveTodoItems(ctx.storyRaw);
  let content: string;
  if (!markDone && !fs.existsSync(file)) {
    content = [
      '# TODO',
      '',
      `Derived from: ${storyExcerpt(ctx)}`,
      '',
      ...items.map((it, i) => `- [ ] ${i + 1}. ${it}`),
      '',
    ].join('\n');
  } else {
    const existing = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
    if (markDone) {
      content =
        existing
          .split('\n')
          .map((line) => line.replace(/^- \[ \] /, '- [x] '))
          .join('\n') +
        (existing.includes('## Done log')
          ? ''
          : `\n## Done log\n\nAll items marked done at ${new Date().toISOString()}.\n`);
    } else {
      content = existing || [
        '# TODO',
        '',
        ...items.map((it, i) => `- [ ] ${i + 1}. ${it}`),
        '',
      ].join('\n');
    }
  }
  fs.writeFileSync(file, content, 'utf8');
  return markDone ? `updated ${file} (all items done)` : `wrote ${file}`;
}

function writeReadme(ctx: ExecContext, file: string, fill: boolean): string {
  ensureParent(file);
  if (!fill || !fs.existsSync(file)) {
    const body = [
      `# ${path.basename(path.dirname(file))}`,
      '',
      '> Generated by Fantasia',
      '',
      '## Story',
      '',
      storyExcerpt(ctx, 300),
      '',
      '## Install',
      '',
      '```bash',
      'cd /workspace/fantasia && npm install',
      '```',
      '',
      '## Run',
      '',
      '```bash',
      'npm start',
      '# then paste a user story, or: npm run demo',
      '```',
      '',
      '## Assumptions',
      '',
      'See [assumptions.md](./assumptions.md).',
      '',
      fill ? '' : '_(stub — content pass pending)_',
      '',
    ];
    if (fill) {
      body.push('## Details', '', 'This deliverable was produced under Fantasia defaults:', '');
      for (const a of ctx.assumptions.slice(0, 5)) {
        body.push(`- ${a.text}`);
      }
      body.push('', '## Status', '', 'Complete (heuristic executor).', '');
    }
    fs.writeFileSync(file, body.join('\n'), 'utf8');
    return `wrote ${file}`;
  }
  // Fill pass: append details if missing
  let cur = fs.readFileSync(file, 'utf8');
  if (!cur.includes('## Details')) {
    cur +=
      '\n## Details\n\nExpanded from story and assumptions.\n\n' +
      ctx.assumptions.map((a) => `- ${a.id}: ${a.text}`).join('\n') +
      '\n';
    fs.writeFileSync(file, cur, 'utf8');
  }
  return `updated ${file}`;
}

function writeServer(ctx: ExecContext, file: string): string {
  ensureParent(file);
  const code = `#!/usr/bin/env node
/**
 * Minimal HTTP handler stub — Fantasia generated
 * Story: ${storyExcerpt(ctx, 80).replace(/\*\//g, '')}
 * Dry-run friendly: require() without listen when FANTASIA_DRY=1
 */
const http = require('http');

function handler(req, res) {
  res.writeHead(200, { 'Content-Type': 'application/json' });
  res.end(JSON.stringify({ ok: true, path: req.url, service: 'fantasia-stub' }));
}

function createServer() {
  return http.createServer(handler);
}

if (require.main === module && process.env.FANTASIA_DRY !== '1') {
  const port = process.env.PORT || 3911;
  createServer().listen(port, () => console.log('listening', port));
}

module.exports = { handler, createServer };
`;
  fs.writeFileSync(file, code, 'utf8');
  return `wrote ${file}`;
}

function writeSmoke(ctx: ExecContext, file: string): string {
  ensureParent(file);
  const serverRel = file.endsWith('.cjs') ? './server.cjs' : './server.js';
  const code = `#!/usr/bin/env node
process.env.FANTASIA_DRY = '1';
const { handler } = require('${serverRel}');
const { EventEmitter } = require('events');

function mockRes() {
  const e = new EventEmitter();
  e.status = 0;
  e.headers = {};
  e.body = '';
  e.writeHead = (s, h) => { e.status = s; e.headers = h; };
  e.end = (b) => { e.body = b; e.emit('end'); };
  return e;
}

const req = { url: '/health' };
const res = mockRes();
handler(req, res);
const parsed = JSON.parse(res.body);
if (!parsed.ok) { console.error('FAIL'); process.exit(1); }
console.log('SMOKE OK', parsed);
`;
  fs.writeFileSync(file, code, 'utf8');
  return `wrote ${file}`;
}

function writeTool(ctx: ExecContext, file: string): string {
  ensureParent(file);
  const code = `#!/usr/bin/env node
/**
 * Fantasia-generated CLI tool
 * ${storyExcerpt(ctx, 100).replace(/\*\//g, '')}
 */
const args = process.argv.slice(2);
if (args.includes('--help') || args.includes('-h')) {
  console.log('Usage: tool.js [--help] [--dry]');
  console.log('Fantasia heuristic tool — processes the canned story context.');
  process.exit(0);
}
console.log('tool: running');
console.log('story:', ${JSON.stringify(storyExcerpt(ctx, 80))});
if (args.includes('--dry')) {
  console.log('dry-run: no side effects');
} else {
  console.log('done');
}
`;
  fs.writeFileSync(file, code, 'utf8');
  try {
    fs.chmodSync(file, 0o755);
  } catch {
    /* ignore */
  }
  return `wrote ${file}`;
}

function writeMain(ctx: ExecContext, file: string): string {
  ensureParent(file);
  const code = `#!/usr/bin/env node
// Fantasia deliverable for: ${storyExcerpt(ctx, 80).replace(/\*\//g, '')}
console.log('Fantasia deliverable');
console.log(${JSON.stringify(storyExcerpt(ctx, 120))});
console.log('status: ok');
`;
  fs.writeFileSync(file, code, 'utf8');
  return `wrote ${file}`;
}

