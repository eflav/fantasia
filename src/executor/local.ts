function writeVerification(ctx: ExecContext, file: string, mid: boolean): string {
  ensureParent(file);
  const dir = slugDir(ctx);
  const expected = ctx.plan.steps
    .filter((s) => s.artifact && s.kind !== 'verify' && s.kind !== 'reflect')
    .map((s) => s.artifact!)
    .filter((a, i, arr) => arr.indexOf(a) === i);

  const results: { path: string; ok: boolean }[] = [];
  for (const rel of expected) {
    const p = abs(ctx, rel);
    results.push({ path: rel, ok: fs.existsSync(p) });
  }
  // Also check dir exists
  results.push({ path: dir.replace(ctx.rootDir + '/', ''), ok: fs.existsSync(dir) });

  const allOk = results.every((r) => r.ok);
  const lines = [
    mid ? '# Mid-run Self-Check' : '# Verification Report',
    '',
    `plan: ${ctx.plan.id}`,
    `time: ${new Date().toISOString()}`,
    `result: ${allOk ? 'PASS' : 'FAIL'}`,
    '',
    '## Checks',
    '',
    ...results.map((r) => `- [${r.ok ? 'x' : ' '}] ${r.path}`),
    '',
    '## Notes',
    '',
    mid
      ? 'Lesson-driven mid-check: confirming artifacts before final verify.'
      : 'Final verification produced by Fantasia local executor.',
    '',
  ];
  fs.writeFileSync(file, lines.join('\n'), 'utf8');
  if (!allOk && !mid) {
    throw new Error(`verification failed: missing ${results.filter((r) => !r.ok).map((r) => r.path).join(', ')}`);
  }
  return `${allOk ? 'PASS' : 'PARTIAL'} → ${file}`;
}

async function runShell(ctx: ExecContext, file: string): Promise<string> {
  const p = abs(ctx, file);
  if (!fs.existsSync(p)) {
    throw new Error(`shell target missing: ${file}`);
  }
  const { stdout, stderr } = await execFileAsync(process.execPath, [p], {
    cwd: path.dirname(p),
    timeout: 15000,
    env: { ...process.env, FANTASIA_DRY: '1' },
  });
  const out = (stdout || '').trim() || (stderr || '').trim() || '(no output)';
  return `ran ${file}: ${out.split('\n')[0]}`;
}

/**
 * Local heuristic executor — writes real artifacts, no API keys.
 */
export async function executeLocal(ctx: ExecContext, step: PlanStep): Promise<string> {
  const file = step.artifact ? abs(ctx, step.artifact) : '';

  switch (step.kind) {
    case 'analyze':
      return `recorded domain analysis for plan ${ctx.plan.id}`;

    case 'create':
    case 'modify': {
      const title = step.title.toLowerCase();
      const art = (step.artifact || '').toLowerCase();

      if (art.endsWith('assumptions.md') || title.includes('assumption')) {
        return writeAssumptionsMd(ctx, file);
      }
      if (art.endsWith('todo.md') || title.includes('checklist') || title.includes('todo')) {
        return writeTodo(ctx, file, title.includes('execute') || title.includes('mark') || title.includes('completion'));
      }
      if (art.endsWith('readme.md') || title.includes('readme')) {
        return writeReadme(ctx, file, title.includes('fill') || title.includes('content') || title.includes('companion'));
      }
      if (art.endsWith('server.js') || art.endsWith('server.cjs') || title.includes('handler') || title.includes('scaffold handler')) {
        return writeServer(ctx, file);
      }
      if (art.endsWith('smoke.js') || art.endsWith('smoke.cjs') || title.includes('smoke script')) {
        return writeSmoke(ctx, file);
      }
      if (art.endsWith('tool.js') || art.endsWith('tool.cjs') || (title.includes('script') && (art.endsWith('.js') || art.endsWith('.cjs')))) {
        return writeTool(ctx, file);
      }
      if (art.endsWith('main.js') || art.endsWith('main.cjs')) {
        return writeMain(ctx, file);
      }
      if (art.endsWith('index.html') || title.includes('html')) {
        return writeHtml(ctx, file, title.includes('interactivity') || title.includes('js'));
      }
      if (art.endsWith('before.md')) {
        ensureParent(file);
        fs.writeFileSync(
          file,
          `# Before\n\n${storyExcerpt(ctx)}\n\nIssues noted:\n- Vague scope\n- No structure\n- Missing verification\n`,
          'utf8'
        );
        return `wrote ${file}`;
      }
      if (art.endsWith('after.md')) {
        ensureParent(file);
        fs.writeFileSync(
          file,
          `# After\n\nImproved structure for: ${storyExcerpt(ctx)}\n\n- Clear sections\n- Assumptions logged\n- Ready for verify\n`,
          'utf8'
        );
        return `wrote ${file}`;
      }
      if (art.endsWith('summary.md')) {
        ensureParent(file);
        fs.writeFileSync(
          file,
          `# Summary\n\nBefore → After refactor complete.\nAssumptions applied: ${ctx.assumptions.length}\n`,
          'utf8'
        );
        return `wrote ${file}`;
      }
      if (art.endsWith('testplan.md')) {
        ensureParent(file);
        fs.writeFileSync(
          file,
          `# Test Plan\n\n1. Artifact exists\n2. Script exits 0\n3. Memory updated\n\nStory: ${storyExcerpt(ctx)}\n`,
          'utf8'
        );
        return `wrote ${file}`;
      }
      if (art.endsWith('assert.js') || art.endsWith('assert.cjs')) {
        ensureParent(file);
        fs.writeFileSync(
          file,
          `#!/usr/bin/env node\nconst fs=require('fs');const path=require('path');\nconst ok=fs.existsSync(path.join(__dirname,'TESTPLAN.md'));\nif(!ok){console.error('FAIL');process.exit(1);}\nconsole.log('ASSERT OK');\n`,
          'utf8'
        );
        return `wrote ${file}`;
      }
      if (art.endsWith('progress.md') || art.endsWith('midcheck.md')) {
        ensureParent(file);
        fs.writeFileSync(
          file,
          `# Progress\n\nCheckpoint at ${new Date().toISOString()}\nPlan: ${ctx.plan.id}\n`,
          'utf8'
        );
        return `wrote ${file}`;
      }
      // Generic create
      ensureParent(file);
      fs.writeFileSync(file, `# ${step.title}\n\n${step.action}\n\n${storyExcerpt(ctx)}\n`, 'utf8');
      return `wrote ${file}`;
    }

    case 'shell':
      return runShell(ctx, step.artifact || '');

    case 'verify':
      return writeVerification(ctx, file, /mid/i.test(step.title));

    case 'reflect':
      return 'reflection handed to engine';

    default:
      return `noop ${step.kind}`;
  }
}
